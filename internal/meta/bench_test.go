func BenchmarkExtractEXIFFromBytes(b *testing.B) {
	b.ReportAllocs()
	for b.Loop() {
		extractEXIFFromBytes(minimalJPEG)
	}
}

func BenchmarkExtractJPEGFile(b *testing.B) {
	f, err := os.CreateTemp(b.TempDir(), "bench*.jpg")
	if err != nil {
		b.Fatal(err)
	}
	if _, err := f.Write(minimalJPEG); err != nil {
		b.Fatal(err)
	}
	f.Close()
	path := f.Name()

	b.ReportAllocs()
	b.ResetTimer()
	for b.Loop() {
		Extract(path)
	}
}

func BenchmarkExtractFallbackMtime(b *testing.B) {
	path := filepath.Join(b.TempDir(), "bench.bin")
	if err := os.WriteFile(path, []byte("not a media file"), 0o644); err != nil {
		b.Fatal(err)
	}

	b.ReportAllocs()
	b.ResetTimer()
	for b.Loop() {
		Extract(path)
	}
}
